/**
 * 1. COMPONENT LOADER
 */
async function loadComponent(id, url) {
    try {
        const response = await fetch(url);
        const html = await response.text();
        document.getElementById(id).innerHTML = html;
        return true;
    } catch (error) {
        console.error('Error loading component:', url, error);
        return false;
    }
}

async function loadAllComponents(lang) {
    await Promise.all([
        loadComponent('nav-placeholder', 'components/nav.html'),
        loadComponent('hero-placeholder', 'components/hero.html'),
        loadComponent('about-placeholder', 'components/about.html'),
        loadComponent('projects-placeholder', 'components/projects.html'),
        loadComponent('achievements-placeholder', 'components/achievements.html'),
        loadComponent('contact-placeholder', 'components/contact.html')
    ]);
    
    initNavFeatures();
    applyLanguage(lang);
}

/**
 * 2. LANGUAGE LOGIC
 */
function getInitialLanguage() {
    const sysLang = navigator.language || navigator.userLanguage;
    return sysLang.startsWith('id') ? 'id' : 'en';
}

function applyLanguage(lang) {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translations[lang][key];
            } else {
                el.textContent = translations[lang][key];
            }
        }
    });
    document.documentElement.lang = lang;
}

/**
 * 3. SPLASH & INITIALIZATION
 */
window.addEventListener('load', () => {
    const splash = document.getElementById('splash-screen');
    const initialLang = getInitialLanguage();
    
    // Load components first
    loadAllComponents(initialLang);
    
    const hideSplash = () => {
        if (splash) {
            splash.classList.add('splash-hidden');
            document.body.style.overflow = 'auto';
            initScrollAnimations();
            initTypewriter(initialLang);
        }
    };
    
    if (splash) {
        splash.addEventListener('click', hideSplash);
    }
});

/**
 * 4. INTERACTIVE FEATURES
 */
function initNavFeatures() {
    const themeBtn = document.getElementById('theme-toggle');
    const langSelect = document.getElementById('lang-select');
    const menuToggle = document.getElementById('menu-toggle');
    const navMenu = document.querySelector('.nav-menu');
    const body = document.body;

    if (langSelect) {
        langSelect.value = document.documentElement.lang || getInitialLanguage();
        langSelect.addEventListener('change', (e) => {
            const lang = e.target.value;
            applyLanguage(lang);
            initTypewriter(lang);
        });
    }

    if (themeBtn) {
        themeBtn.addEventListener('click', () => {
            body.classList.toggle('light-mode');
            const icon = themeBtn.querySelector('i');
            if (icon) {
                icon.classList.toggle('fa-moon');
                icon.classList.toggle('fa-sun');
            }
        });
    }

    if (menuToggle && navMenu) {
        menuToggle.addEventListener('click', (e) => {
            e.stopPropagation();
            navMenu.classList.toggle('active');
            const icon = menuToggle.querySelector('i');
            if (icon) {
                icon.classList.toggle('fa-bars');
                icon.classList.toggle('fa-times');
            }
        });

        // Close menu when clicking outside
        document.addEventListener('click', (e) => {
            if (navMenu.classList.contains('active') && !navMenu.contains(e.target) && !menuToggle.contains(e.target)) {
                navMenu.classList.remove('active');
                const icon = menuToggle.querySelector('i');
                if (icon) {
                    icon.classList.add('fa-bars');
                    icon.classList.remove('fa-times');
                }
            }
        });

        // Close menu when clicking a nav item
        const navLinks = navMenu.querySelectorAll('.nav-item');
        navLinks.forEach(link => {
            link.addEventListener('click', () => {
                navMenu.classList.remove('active');
                const icon = menuToggle.querySelector('i');
                if (icon) {
                    icon.classList.add('fa-bars');
                    icon.classList.remove('fa-times');
                }
            });
        });
    }

    // Scroll Spy — update active nav item based on scroll position
    window.addEventListener('scroll', () => {
        const sections = document.querySelectorAll('section[id]');
        const navItems = document.querySelectorAll('.nav-item');
        let current = '';

        sections.forEach(section => {
            const sectionTop = section.offsetTop - 120;
            if (window.scrollY >= sectionTop) {
                current = section.getAttribute('id');
            }
        });

        navItems.forEach(item => {
            item.classList.remove('active');
            if (item.getAttribute('href') === `#${current}`) {
                item.classList.add('active');
            }
        });
    });
}

function initScrollAnimations() {
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) entry.target.classList.add('active');
        });
    }, { threshold: 0.1 });
    document.querySelectorAll('.reveal').forEach(el => observer.observe(el));
}

let phraseTimeout;
function initTypewriter(lang = 'id') {
    const textElement = document.getElementById('typewriter');
    if (!textElement) return;
    
    if (phraseTimeout) clearTimeout(phraseTimeout);

    const phrases = lang === 'en' 
        ? ["Full-stack Developer", "Martial Arts Athlete", "Informatics Student", "UI/UX Designer"]
        : ["Pengembang Full-stack", "Atlet Bela Diri", "Mahasiswa Informatika", "Desainer UI/UX"];
    
    let i = 0;
    textElement.textContent = phrases[0];
    textElement.style.opacity = 1;

    function loop() {
        phraseTimeout = setTimeout(() => {
            textElement.style.opacity = 0;
            setTimeout(() => {
                i = (i + 1) % phrases.length;
                textElement.textContent = phrases[i];
                textElement.style.opacity = 1;
                loop();
            }, 500);
        }, 2500);
    }
    loop();
}